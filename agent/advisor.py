from langchain.chat_models import init_chat_model

def advise(loan: dict, analysis: dict) -> str:
    model = init_chat_model("gpt-4-turbo")
    prompt = f"""
Пользователь рассматривает кредит:
- Банк: {loan.get('bank', 'не указан')}
- Сумма: {loan.get('sum')} тенге
- Ставка: {loan.get('annual_rate')}%
- Срок: {loan.get('months')} месяцев

Результаты анализа:
- Ежемесячный платёж: {analysis['monthly_payment']} тенге
- Общая сумма выплат: {analysis['total_payment']} тенге
- Переплата: {analysis['overpayment']} тенге

Правила оценки:
- Если переплата > 50% от суммы — предупреди что кредит дорогой
- Если ставка выше средней по рынку (25%) — укажи это явно  
- Если есть альтернатива дешевле на 20%+ — настоятельно рекомендуй
- Если не хватает данных для расчёта — спроси конкретно что нужно
- Всегда указывай на что обратить внимание: комиссии, штрафы, страховки
Похожие предложения других банков:
{analysis['similar_offers']}

Дай краткий финансовый совет: выгодно ли это предложение?
Сравни с альтернативами и порекомендуй лучший вариант.
Отвечай на русском, кратко и по делу.
"""
    response = model.invoke([{"role": "user", "content": prompt}])
    return response.content